#!/usr/bin/env python3
"""Build readable picture attribution from the committed source records."""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PICS = ROOT / 'assets/pictures'

def plain(value):
    return re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', '', value))).strip()

def main():
    records = json.loads((PICS / 'sources.json').read_text(encoding='utf-8'))
    records += [dict(x, file='../clue-photos/'+x['file']) for x in json.loads((ROOT / 'assets/clue-photos/sources.json').read_text())]
    text = '''# Picture credits

Photographs, costume photos, figurines and road-sign artwork were downloaded from Wikimedia Commons. Each entry links to the original file, author and full licensing terms. Commons preview sizes are used. Exact source records are in `sources.json`.

Entertainment decks also use generated illustrations and object-and-scene visual riddles. These are quiz clues; franchise characters and names belong to their respective owners. Illustration-sheet records are in `../clue-atlases/sources.json`. Each sheet has six cells, and only the current clue's cell is sent to the audience.

## Downloaded images

'''
    for r in sorted(records, key=lambda r: r['file']):
        text += f"- **{r['file']}** — {plain(r['artist']) or 'See original file for author'}; {plain(r['license'])}. [Original file and licensing terms]({r['source']})."
        if r.get('license_url'):
            text += ' License: ' + r['license_url'] + '.'
        if r.get('note'):
            text += ' ' + plain(r['note']) + '.'
        text += '\n'
    text += '''
## Original chemical-symbol artwork

The 30 Chemical Symbols SVGs are original artwork generated by `tools/build_picture_symbols.py` for this project and released under CC0-1.0. Chemical symbols follow standard element notation. The host supplies the element name.

## Generated illustration sheets

'''
    sheets = json.loads((ROOT / 'assets/clue-atlases/sources.json').read_text(encoding='utf-8'))
    for sheet in sheets:
        text += '- **' + sheet['file'] + '** — generated on ' + sheet['created'] + '; categories: ' + ', '.join(sheet['categories']) + '.\n'
    text += '''
## Original visual diagrams and question sources

The text-free prop and traditional-game diagrams in `../clue-symbols/` are original project artwork, released under CC0-1.0 and generated by `tools/build_clue_symbols.py`. Original short questions and their factual references are recorded in `data/picture_questions.json`, compiled from `tools/src/picture_*.txt`. A question can use a relevant actor portrait, object, or scene as its visual anchor.

## Quiz notes

Food includes African and international dishes. Accept familiar regional names (for example, pap or ugali; eggplant or aubergine). African games can share boards and rules: accept related traditional names where the pictured equipment cannot distinguish variants. K53 clues use South African/SADC sign designs. Entertainment clues may identify a franchise from its signature props, costumes, creatures or scenes. Accept related editions where the clue fits more than one (for example, Dragon Ball or Dragon Ball Z). Football categories are a snapshot reviewed on 10 November 2026.

## GNU Free Documentation License

For images offered under the GNU Free Documentation License, permission is granted to copy, distribute and/or modify them under the GNU Free Documentation License, Version 1.2 or any later version published by the Free Software Foundation, with no Invariant Sections, no Front-Cover Texts, and no Back-Cover Texts. A full copy is included in [GFDL-1.2.txt](GFDL-1.2.txt). For multi-licensed files, you may choose the Creative Commons license listed in the individual record.
'''
    (PICS / 'CREDITS.md').write_text(text, encoding='utf-8')
    print(f'Wrote credits for {len(records)} downloaded images and {len(sheets)} illustration sheets')

if __name__ == '__main__':
    main()
