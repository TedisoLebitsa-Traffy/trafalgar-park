#!/usr/bin/env python3
"""Build data/taboo_sa.js (extra South African Taboo cards) from tools/src/taboo_sa_normal.txt and taboo_sa_hard.txt.

Each source line is   Target|candidate1,candidate2,...   (best first). The builder keeps the first 3 (Normal) / 4 (Hard) candidates that
  * are not themselves a card in EITHER pool (so a forbidden word is never another card),
  * share no word with the target (no "Day" forbidden on "Day Zero"),
and drops any card whose target already exists as a card or as a forbidden word on an existing card.
Run:  python tools/build_taboo_sa.py     (needs Node.js only to read the existing deck)
"""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NEED = {"normal": 3, "hard": 4}

dump = subprocess.run(["node", "-e",
    "const D=require(%s)(['taboo.js']);console.log(JSON.stringify(D.taboo))" % json.dumps(os.path.join(ROOT, "tests", "load.js").replace("\\", "/"))],
    capture_output=True, text=True, check=True).stdout
base = json.loads(dump)
low = lambda s: s.strip().lower()
toks = lambda s: {t.rstrip("s") for t in re.findall(r"[a-z0-9']+", s.lower()) if len(t) > 2}

existing_targets, existing_forbidden = set(), set()
for pool in ("normal", "hard"):
    for c in base[pool]:
        existing_targets.add(low(c[0]))
        existing_forbidden.update(low(w) for w in c[1:])

import glob


def read(name):
    rows = []
    files = sorted(glob.glob(os.path.join(ROOT, "tools", "src", "taboo_sa_%s*.txt" % name)))
    lines = [l for f in files for l in open(f, encoding="utf-8")]
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#") or "|" not in line or "? skip" in line:
            continue
        t, c = line.split("|", 1)
        rows.append((t.strip(), [w.strip() for w in c.split(",") if w.strip()]))
    return rows

src = {p: read(p) for p in ("normal", "hard")}
new_targets, kept, dropped = set(), {"normal": [], "hard": []}, []
# pass 1: which targets are allowed
for pool in ("normal", "hard"):
    for t, c in src[pool]:
        k = low(t)
        if k in existing_targets or k in existing_forbidden or k in new_targets:
            dropped.append((pool, t, "duplicate / already used as a card or a forbidden word"))
            continue
        new_targets.add(k)
        kept[pool].append((t, c))
all_targets = existing_targets | new_targets
# pass 2: pick forbidden words
out = {"normal": [], "hard": []}
for pool in ("normal", "hard"):
    for t, cands in kept[pool]:
        tt, picked = toks(t), []
        for w in cands:
            k = low(w)
            if k in all_targets or k in (low(p) for p in picked):
                continue
            wt = toks(w)
            if wt & tt or low(t) in k or k in low(t):
                continue
            picked.append(w)
            if len(picked) == NEED[pool]:
                break
        if len(picked) < NEED[pool]:
            dropped.append((pool, t, "not enough clean forbidden words"))
            continue
        out[pool].append([t] + picked)

js = ["/* Extra TABOO cards about South Africa (politics, places, sport, culture, current affairs). GENERATED by tools/build_taboo_sa.py",
      "   from tools/src/taboo_sa_*.txt - edit those files and re-run the builder. Verified against news on 2026-11-02:",
      "   local government elections 4 Nov 2026 (proclaimed by Minister Hlabisa), Madlanga Commission, Phala Phala impeachment committee,",
      "   Bafana Bafana's first World Cup knockout round (2026), Navi Pillay's 2026 Nobel Peace Prize. */",
      "window.TPData=window.TPData||{};",
      "TPData.taboo.verifiedSA='2026-11-02';"]
for pool in ("normal", "hard"):
    js.append("TPData.taboo.%s.push(" % pool)
    js.append(",\n".join(json.dumps(c, ensure_ascii=False) for c in out[pool]))
    js.append(");")
open(os.path.join(ROOT, "data", "taboo_sa.js"), "w", encoding="utf-8").write("\n".join(js) + "\n")
print("existing: normal %d  hard %d" % (len(base["normal"]), len(base["hard"])))
print("added:    normal %d  hard %d" % (len(out["normal"]), len(out["hard"])))
print("totals:   normal %d  hard %d   (3x = %d / %d)" % (len(base["normal"]) + len(out["normal"]), len(base["hard"]) + len(out["hard"]), 3 * len(base["normal"]), 3 * len(base["hard"])))
for d in dropped:
    print("  dropped [%s] %s - %s" % d)
